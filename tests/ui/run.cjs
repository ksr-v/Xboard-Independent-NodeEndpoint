'use strict';
const { chromium } = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const base = process.env.NE_UI_BASE || 'http://127.0.0.1:18743';
  if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw new Error('UI fixture must be loopback');
  const authPath = process.env.NE_UI_AUTH || path.join(__dirname, '../integration/work/ui-fixture/fixture-auth.json');
  const auth = JSON.parse(fs.readFileSync(authPath, 'utf8'));
  const fixtureToken = auth.admin_token || auth.admin || auth.token;
  if (typeof fixtureToken !== 'string') throw new Error('Synthetic fixture administrator token missing');
  const output = path.join(__dirname, 'work'); fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ channel: process.env.NE_BROWSER_CHANNEL || 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1360, height: 900 } });
  const page = await context.newPage(); const errors = [], passed = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(base + '/node-endpoint');
    assert.equal(await page.title(), '节点通讯设置 · NodeEndpoint');
    assert.equal(await page.locator('#login-panel').isVisible(), true);
    assert.equal(await page.locator('#workspace').isVisible(), false);
    await page.screenshot({ path: path.join(output, 'login-desktop.png'), fullPage: true });
    passed.push('public login shell hides sensitive workspace');
    await page.locator('summary').click();
    await page.locator('#admin-token').fill(fixtureToken);
    await page.locator('#token-form button').click();
    await page.locator('#workspace').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#admin-token').inputValue(), '');
    assert.deepEqual(await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage) })), { local: [], session: [] });
    passed.push('native administrator API login with memory-only token');
    await page.locator('#enabled').check();
    await page.locator('#https').check();
    await page.locator('#host').fill('2001:db8::1');
    await page.locator('#port').fill('8443');
    assert.equal(await page.locator('#url').textContent(), 'https://[2001:db8::1]:8443');
    assert.equal(await page.locator('#ws-url').textContent(), 'wss://[2001:db8::1]:8443/ws');
    passed.push('IPv6 preview brackets and HTTPS/WSS schemes');
    await page.locator('#https').uncheck();
    assert.equal(await page.locator('#http-risk').isVisible(), true);
    await page.locator('#http-ack').uncheck();
    await page.locator('#settings-form button[type="submit"], #settings-form .actions button').first().click();
    await page.waitForFunction(() => document.getElementById('notice').className === 'error');
    assert.match(await page.locator('#notice').textContent(), /显式确认/);
    passed.push('HTTP without administrator acknowledgement rejected by real API');
    await page.locator('#http-ack').check();
    await page.locator('#host').fill('198.51.100.17');
    await page.locator('#settings-form .actions button').first().click();
    await page.waitForFunction(() => document.getElementById('notice').textContent.includes('仅保存插件设置'));
    assert.equal(await page.locator('#url').textContent(), 'http://198.51.100.17:8443');
    assert.equal(await page.locator('#ws-url').textContent(), 'ws://198.51.100.17:8443/ws');
    passed.push('acknowledged HTTP saved and WS derived');
    await page.locator('#identity').fill('7');
    await page.locator('#unused-identity').check();
    await page.locator('#command-form button').click();
    await page.waitForFunction(() => document.getElementById('command-result').textContent.includes('--allow-http'));
    const command = await page.locator('#command-result').textContent();
    assert.match(command, /--mode' 'node/); assert.match(command, /--node-id' '7/);
    assert.match(command, /--confirm-new-identity' 'UNUSED/);
    assert.equal(command.includes(fixtureToken), false);
    passed.push('new node command matches CLI and contains no Token');
    await page.locator('#node-type').selectOption('anytls');
    await page.locator('#kernel').selectOption('xray');
    assert.equal(await page.locator('#node-type').inputValue(), 'vless');
    assert.equal(await page.locator('#node-type option').filter({ hasText: /^anytls$/ }).evaluate(option => option.disabled), true);
    assert.equal(await page.locator('#node-type option').filter({ hasText: /^tuic$/ }).evaluate(option => option.disabled), true);
    assert.equal(await page.locator('#node-type option').filter({ hasText: /^hysteria2$/ }).evaluate(option => option.disabled), false);
    await page.locator('#kernel').selectOption('singbox');
    assert.equal(await page.locator('#node-type option').filter({ hasText: /^anytls$/ }).evaluate(option => option.disabled), false);
    await page.locator('#mode').selectOption('machine');
    assert.equal(await page.locator('#type-label').isVisible(), false);
    await page.locator('#kernel').selectOption('xray');
    await page.locator('#architecture').selectOption('arm64');
    await page.locator('#unused-identity').check();
    await page.locator('#command-form button').click();
    await page.waitForFunction(() => document.getElementById('command-result').textContent.includes("--machine-id' '7"));
    assert.match(await page.locator('#command-result').textContent(), /--architecture' 'arm64/);
    passed.push('machine Xray ARM64 command and node-type visibility');
    await page.locator('#host').fill('node.example.test');
    await page.locator('#https').check();
    await page.locator('#settings-form .actions button').first().click();
    await page.waitForFunction(() => document.getElementById('notice').textContent.includes('仅保存插件设置'));
    await page.screenshot({ path: path.join(output, 'settings-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'settings-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    passed.push('desktop and mobile layout without horizontal overflow');
    await page.reload();
    assert.equal(await page.locator('#workspace').isVisible(), false);
    passed.push('refresh clears administrator session');
    assert.deepEqual(errors, []);
    const result = { passed: passed.length, checks: passed, browser: browser.version(), base, page_errors: errors };
    fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result, null, 2));
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error(error.stack || error.message); process.exitCode = 1; });
